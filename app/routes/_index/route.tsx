import type { LoaderFunctionArgs } from "react-router";
import { redirect, Form, useLoaderData } from "react-router";

import { login } from "../../shopify.server";

import styles from "./styles.module.css";

export const loader = async ({ request }: LoaderFunctionArgs) => {
  const url = new URL(request.url);

  if (url.searchParams.get("shop")) {
    throw redirect(`/app?${url.searchParams.toString()}`);
  }

  return { showForm: Boolean(login) };
};

export default function App() {
  const { showForm } = useLoaderData<typeof loader>();

  return (
    <div className={styles.index}>
      <div className={styles.content}>
        <h1 className={styles.heading}>Catalog Copilot</h1>
        <p className={styles.text}>
          Find incomplete product listings and review AI-suggested improvements before anything is published.
        </p>
        {showForm && (
          <Form className={styles.form} method="post" action="/auth/login">
            <label className={styles.label}>
              <span>Shop domain</span>
              <input className={styles.input} type="text" name="shop" />
              <span>e.g: my-shop-domain.myshopify.com</span>
            </label>
            <button className={styles.button} type="submit">
              Log in
            </button>
          </Form>
        )}
        <ul className={styles.list}>
          <li>
            <strong>Find gaps</strong>. See which products are missing a
            description or tags.
          </li>
          <li>
            <strong>Grounded suggestions</strong>. Draft descriptions and tags
            from the facts already on the product.
          </li>
          <li>
            <strong>You approve every change</strong>. Nothing is published
            without your explicit review.
          </li>
        </ul>
      </div>
    </div>
  );
}
